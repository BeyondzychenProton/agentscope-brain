package com.agentscope.brain.projection.internal.application;

import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.nio.charset.StandardCharsets;
import java.time.LocalDateTime;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.transaction.support.TransactionTemplate;
import static org.assertj.core.api.Assertions.*;

class StreamingReplyWriterTest {
    private final ObjectMapper json = new ObjectMapper();
    private final LocalDateTime now = LocalDateTime.of(2026, 10, 27, 12, 0, 0);
    private final byte[] stream = uuidBytes("11111111-1111-1111-1111-111111111111");
    private final byte[] callKey = uuidBytes("22222222-2222-2222-2222-222222222222");
    private JdbcTemplate jdbc;
    private TransactionTemplate tx;
    private StreamingReplyWriter writer;

    @BeforeEach void setUp() {
        var source = new DriverManagerDataSource(
                "jdbc:h2:mem:stream-reply-" + UUID.randomUUID() + ";MODE=MySQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(source);
        tx = new TransactionTemplate(new DataSourceTransactionManager(source));
        writer = new StreamingReplyWriter(jdbc, new HistoryCursor(java.util.Base64.getEncoder().encodeToString(new byte[32])));
        jdbc.execute("""
            CREATE TABLE business_session(
              id BIGINT PRIMARY KEY,user_id BIGINT,title VARCHAR(200),row_version BIGINT,
              projection_stream_id BINARY(16),last_projection_seq BIGINT,last_message_no BIGINT,
              gmt_modified TIMESTAMP)
            """);
        jdbc.execute("""
            CREATE TABLE runtime_sdk_call(id BIGINT PRIMARY KEY,sdk_call_key BINARY(16))
            """);
        jdbc.execute("""
            CREATE TABLE run_progress(
              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              run_id BIGINT,event_no BIGINT,event_kind VARCHAR(24),display_text CLOB,
              occurred_at TIMESTAMP,gmt_create TIMESTAMP,gmt_modified TIMESTAMP,
              payload_version INT,structured_payload CLOB,content_id BINARY(16),content_version BIGINT,
              sdk_call_key BINARY(16),source_kind VARCHAR(24),source_id BIGINT,
              first_projection_seq BIGINT,first_projection_position SMALLINT,
              content_status VARCHAR(16),close_reason VARCHAR(16),replacement_message_id BIGINT,
              projection_stream_id BINARY(16),projection_seq BIGINT,projection_position SMALLINT)
            """);
        jdbc.execute("""
            CREATE TABLE projection_content(
              content_id BINARY(16) PRIMARY KEY,owner_user_id BIGINT,session_id BIGINT,run_id BIGINT,
              content_kind VARCHAR(24),stream_id BINARY(16),first_seq BIGINT,first_position SMALLINT,
              current_version BIGINT,status VARCHAR(16),close_reason VARCHAR(16),
              replacement_message_id BIGINT,gmt_create TIMESTAMP,gmt_modified TIMESTAMP)
            """);
        jdbc.execute("""
            CREATE TABLE projection_content_version(
              content_id BINARY(16),content_version BIGINT,base_version BIGINT,change_kind VARCHAR(24),
              content_status VARCHAR(16),close_reason VARCHAR(16),replacement_message_id BIGINT,
              body_format VARCHAR(24),payload_storage VARCHAR(16),body BLOB,byte_count INT,
              body_sha256 BINARY(32),source_kind VARCHAR(24),source_id BIGINT,
              projection_seq BIGINT,projection_position SMALLINT,
              gmt_create TIMESTAMP,gmt_modified TIMESTAMP,
              PRIMARY KEY(content_id,content_version))
            """);
        jdbc.execute("""
            CREATE TABLE session_projection_event(
              session_id BIGINT,stream_id BINARY(16),seq BIGINT,previous_seq BIGINT,
              protocol_version VARCHAR(32),batch_payload BLOB,byte_count INT,batch_sha256 BINARY(32),
              change_count INT,occurred_at TIMESTAMP,gmt_create TIMESTAMP,gmt_modified TIMESTAMP)
            """);
        jdbc.update("""
            INSERT INTO business_session(id,user_id,title,row_version,projection_stream_id,last_projection_seq,last_message_no,gmt_modified)
            VALUES(10,100,'t',1,?,0,1,?)
            """, stream, now);
        jdbc.update("INSERT INTO runtime_sdk_call(id,sdk_call_key) VALUES(50,?)", callKey);
    }

    @Test void openThenAppendWritesContentSetAndTextAppendBatches() throws Exception {
        StreamingReplyWriter.Handle first = tx.execute(status -> writer.publishCumulative(ctx(), "你好", now));
        assertThat(first).isNotNull();
        assertThat(first.contentVersion()).isEqualTo("1");

        StreamingReplyWriter.Handle second = tx.execute(status -> writer.publishCumulative(ctx(), "你好世界", now));
        assertThat(second.contentId()).isEqualTo(first.contentId());
        assertThat(second.contentVersion()).isEqualTo("2");

        var events = jdbc.queryForList(
                "SELECT seq,change_count,batch_payload FROM session_projection_event WHERE session_id=10 ORDER BY seq");
        assertThat(events).hasSize(2);
        assertThat(events.get(0).get("change_count")).isEqualTo(1);
        Map<String, Object> batch1 = json.readValue((byte[]) events.get(0).get("batch_payload"), new TypeReference<>() { });
        assertThat(batch1.get("protocolVersion")).isEqualTo("web-projection-v1");
        @SuppressWarnings("unchecked")
        List<Map<String, Object>> changes1 = (List<Map<String, Object>>) batch1.get("changes");
        assertThat(changes1.get(0).get("type")).isEqualTo("CONTENT_SET");
        assertThat(changes1.get(0).get("status")).isEqualTo("OPEN");

        Map<String, Object> batch2 = json.readValue((byte[]) events.get(1).get("batch_payload"), new TypeReference<>() { });
        @SuppressWarnings("unchecked")
        List<Map<String, Object>> changes2 = (List<Map<String, Object>>) batch2.get("changes");
        assertThat(changes2.get(0).get("type")).isEqualTo("TEXT_APPEND");
        assertThat(changes2.get(0).get("delta")).isEqualTo("世界");
        assertThat(changes2.get(0).get("baseContentVersion")).isEqualTo("1");
        assertThat(changes2.get(0).get("contentVersion")).isEqualTo("2");

        assertThat(jdbc.queryForObject("SELECT status FROM projection_content WHERE run_id=20", String.class))
                .isEqualTo("OPEN");
        assertThat(jdbc.queryForObject("SELECT current_version FROM projection_content WHERE run_id=20", Long.class))
                .isEqualTo(2L);
        assertThat(jdbc.queryForObject("SELECT last_projection_seq FROM business_session WHERE id=10", Long.class))
                .isEqualTo(2L);
    }

    @Test void identicalCumulativeIsNoOp() {
        tx.execute(status -> writer.publishCumulative(ctx(), "same", now));
        tx.execute(status -> writer.publishCumulative(ctx(), "same", now));
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM session_projection_event", Long.class)).isEqualTo(1L);
    }

    @Test void closeInterruptedAllowsFreshPreviewAfterTools() {
        StreamingReplyWriter.Handle opened = tx.execute(status -> writer.publishCumulative(ctx(), "a", now));
        tx.execute(status -> {
            writer.close(ctx(), opened.contentId(), "INTERRUPTED", null, now);
            return null;
        });
        assertThat(jdbc.queryForObject(
                "SELECT close_reason FROM projection_content WHERE run_id=20 AND status='CLOSED'", String.class))
                .isEqualTo("INTERRUPTED");
        StreamingReplyWriter.Handle next = tx.execute(status -> writer.publishCumulative(ctx(), "新一轮", now));
        assertThat(next.contentId()).isNotEqualTo(opened.contentId());
        assertThat(jdbc.queryForObject(
                "SELECT COUNT(*) FROM projection_content WHERE run_id=20 AND status='OPEN'", Long.class))
                .isEqualTo(1L);
    }

    @Test void promoteSetsReplacementAndRejectsAppend() {
        StreamingReplyWriter.Handle opened = tx.execute(status -> writer.publishCumulative(ctx(), "final", now));
        tx.execute(status -> {
            writer.close(ctx(), opened.contentId(), "PROMOTED", "99", now);
            return null;
        });
        assertThat(jdbc.queryForObject("SELECT status FROM projection_content WHERE run_id=20", String.class))
                .isEqualTo("PROMOTED");
        assertThat(jdbc.queryForObject(
                "SELECT replacement_message_id FROM projection_content WHERE run_id=20", Long.class))
                .isEqualTo(99L);
    }

    @Test void rejectsBodyOver256KiB() {
        String huge = "x".repeat(262145);
        assertThatThrownBy(() -> tx.execute(status -> writer.publishCumulative(ctx(), huge, now)))
                .isInstanceOf(IllegalArgumentException.class)
                .hasMessageContaining("ASSISTANT_TEXT_INVALID");
    }

    private StreamingReplyWriter.Context ctx() {
        return new StreamingReplyWriter.Context("100", "10", "20", "50");
    }

    private static byte[] uuidBytes(String value) {
        var id = UUID.fromString(value);
        return java.nio.ByteBuffer.allocate(16)
                .putLong(id.getMostSignificantBits())
                .putLong(id.getLeastSignificantBits())
                .array();
    }
}
